const qid = id => id.replace(/[^a-z0-9]/gi, '_');

async function callWithRetry(req) {
  const J = require('../../server/lib/jevAudit');
  for (let attempt = 0; ; attempt++) {
    const t0 = Date.now();
    try { const r = await J.callJev(req); r.ms = Date.now() - t0; return r; } catch (e) {
      if (!/HTTP (429|5\d\d)|fetch failed|ECONNRESET|ETIMEDOUT/.test(e.message) || attempt >= 3) throw e;
      await new Promise(res => setTimeout(res, 2000 * (attempt + 1)));
    }
  }
}

async function run() {
  if (!fs.existsSync(LABELS)) throw new Error('reading labels first: the labels are written before any Jev call');
  const items = loadItems();
  const reps = Number(argv.reps || 3);
  const capUsd = Number(argv.capUsd || 0.15);
  fs.mkdirSync(RUN_DIR, { recursive: true });
  const prior = fs.existsSync(ANSWERS) ? fs.readFileSync(ANSWERS, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse) : [];
  const done = new Set(prior.map(a => `${a.id}|${a.variant}|${a.rep}`));
  let cost = prior.reduce((s, a) => s + (a.cost || 0), 0);
  const tasks = [];
  for (const it of items) for (const rq of requests(it)) for (let rep = 0; rep < reps; rep++) if (!done.has(`${rq.id}|${rq.variant}|${rep}`)) tasks.push({ rq, rep });
  console.log(`${tasks.length} calls to make (spent so far $${cost.toFixed(5)}, cap $${capUsd})`);
  const out = fs.createWriteStream(ANSWERS, { flags: 'a' });
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(Number(argv.conc || 6), tasks.length) }, async () => {
    while (next < tasks.length) {
      if (cost > capUsd) throw new Error(`cap $${capUsd} reached`);
      const { rq, rep } = tasks[next++];
      const r = await callWithRetry({ state: rq.state, questions: rq.questions });
      cost += r.cost;
      out.write(JSON.stringify({ id: rq.id, variant: rq.variant, rep, answers: r.answers, cost: r.cost, ms: r.ms, nq: Object.keys(rq.questions).length }) + '\n');
    }
  }));
  out.end();
  console.log(`done, total $${cost.toFixed(5)}`);
}

// ───────────────────────── score ─────────────────────────

const mean = xs => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN);
const r3 = x => (Number.isFinite(x) ? +x.toFixed(3) : null);
const pct = (xs, q) => { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.min(s.length - 1, Math.floor(q * s.length))] : null; };
function auc(pos, neg) {
  if (!pos.length || !neg.length) return null;
  let s = 0;
  for (const p of pos) for (const q of neg) s += p > q ? 1 : p === q ? 0.5 : 0;
  return s / (pos.length * neg.length);
}
const entropyBits = counts => { const n = counts.reduce((a, b) => a + b, 0); return -counts.filter(Boolean).reduce((s, c) => s + (c / n) * Math.log2(c / n), 0); };

/**
 * TWO DRAW POLICIES, measured side by side:
 *   P1 absolute: the top DRAW_TOP shapes whose mean P(yes) is at least DRAW_FLOOR; nothing clears
 *      the floor → the band's own shape is kept.
 *   P2 relative: the top DRAW_TOP shapes within DRAW_MARGIN of the top one — always a draw.
 * One shape is drawn with probability ∝ P among the candidates.
 */
const DRAW_TOP = 3;
const DRAW_FLOOR = 0.5;
const DRAW_MARGIN = 0.1;
function drawDistribution(ranked, band, policy) {
  const cands = policy === 'P1'
    ? ranked.slice(0, DRAW_TOP).filter(x => x.p >= DRAW_FLOOR)
    : ranked.slice(0, DRAW_TOP).filter(x => x.p >= ranked[0].p - DRAW_MARGIN);
  if (!cands.length) return { [BAND_DEFAULT[band]]: 1 };
  const z = cands.reduce((s, x) => s + x.p, 0);
  return Object.fromEntries(cands.map(x => [x.id, x.p / z]));
}

function score() {
  const items = loadItems();
  const labels = JSON.parse(fs.readFileSync(LABELS, 'utf8'));
  const answers = fs.readFileSync(ANSWERS, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse);
  const metrics = { generatedAt: new Date().toISOString(), drawPolicy: { top: DRAW_TOP, floor: DRAW_FLOOR, margin: DRAW_MARGIN }, variants: {} };
  for (const variant of Object.keys(VARIANTS)) {
    const perSetup = [];
    const pooledG = [], pooledB = [], pooledN = [];
    const withinAucs = [];
    let flips = 0, flipPairs = 0; const dAbs = [];
    for (const it of items) {
      const rows = answers.filter(a => a.id === it.setup && a.variant === variant);
      if (!rows.length) continue;
      const ids = BAND_SETS[it.setKey];
      const byRep = rows.map(r => Object.fromEntries(ids.map(id => [id, r.answers[qid(id)].noul])));
      const p = Object.fromEntries(ids.map(id => [id, mean(byRep.map(b => b[id]))]));
      const ranked = ids.map(id => ({ id, p: p[id] })).sort((a, b) => b.p - a.p);
      const lab = labels[it.setup] || {};
      for (const id of ids) (lab[id] === 'G' ? pooledG : lab[id] === 'B' ? pooledB : pooledN).push(p[id]);
      const wa = auc(ids.filter(id => lab[id] === 'G').map(id => p[id]), ids.filter(id => lab[id] === 'B').map(id => p[id]));
      if (wa !== null) withinAucs.push(wa);
      const tops = byRep.map(b => ids.slice().sort((x, y) => b[y] - b[x])[0]);
      for (let i = 0; i < tops.length; i++) for (let j = i + 1; j < tops.length; j++) { flipPairs++; if (tops[i] !== tops[j]) flips++; }
      for (const id of ids) for (let i = 0; i < byRep.length; i++) for (let j = i + 1; j < byRep.length; j++) dAbs.push(Math.abs(byRep[i][id] - byRep[j][id]));
      // single-call flip: one call's top pick vs the 3-call mean's
      const singleTopAgree = tops.filter(t => t === ranked[0].id).length / tops.length;
      const draw = {}; const drawLabel = {};
      for (const pol of ['P1', 'P2']) {
        draw[pol] = drawDistribution(ranked, it.setKey, pol);
        drawLabel[pol] = { G: 0, N: 0, B: 0 };
        for (const [id, w] of Object.entries(draw[pol])) drawLabel[pol][lab[id] || 'N'] += w;
      }
      const round = o => Object.fromEntries(Object.entries(o).map(([pol, d]) => [pol, Object.fromEntries(Object.entries(d).map(([k, v]) => [k, r3(v)]))]));
      perSetup.push({
        setup: it.setup, band: it.setKey, today: BAND_DEFAULT[it.setKey], todayLabel: lab[BAND_DEFAULT[it.setKey]] || null,
        ranked: ranked.map(x => ({ id: x.id, p: r3(x.p), label: lab[x.id] || null })),
        top1: ranked[0].id, top1Label: lab[ranked[0].id] || null, singleTopAgree: r3(singleTopAgree),
        withinAuc: r3(wa), draw: round(draw), drawLabel: round(drawLabel),
      });
    }
    const cnt = (xs, k) => xs.filter(x => x === k).length;
    const top1Labels = perSetup.map(s => s.top1Label);
    const todayLabels = perSetup.map(s => s.todayLabel);
    // spread, age 5+ only (every one of those books is a hero's journey today)
    const older = perSetup.filter(s => s.band.startsWith('journey'));
    const topCounts = {}; for (const s of older) topCounts[s.top1] = (topCounts[s.top1] || 0) + 1;
    const spreadOf = (pol) => {
      const m = {}; for (const s of older) for (const [id, w] of Object.entries(s.draw[pol])) m[id] = (m[id] || 0) + w;
      return {
        drawMass: Object.fromEntries(Object.entries(m).sort((a, b) => b[1] - a[1]).map(([k, v]) => [k, r3(v)])),
        drawEntropyBits: r3(entropyBits(Object.values(m))),
        heroJourneyShareOfDraws: r3((m['hero-journey'] || 0) / older.length),
      };
    };
    const allCosts = answers.filter(a => a.variant === variant);
    metrics.variants[variant] = {
      setups: perSetup.length,
      pooledAucGvsB: r3(auc(pooledG, pooledB)), pooledAucGvsNB: r3(auc(pooledG, [...pooledN, ...pooledB])),
      meanWithinSetupAucGvsB: r3(mean(withinAucs)), withinSetups: withinAucs.length,
      meanP: { G: r3(mean(pooledG)), N: r3(mean(pooledN)), B: r3(mean(pooledB)) },
      top1: { G: cnt(top1Labels, 'G'), N: cnt(top1Labels, 'N'), B: cnt(top1Labels, 'B') },
      todayShape: { G: cnt(todayLabels, 'G'), N: cnt(todayLabels, 'N'), B: cnt(todayLabels, 'B') },
      drawExpected: Object.fromEntries(['P1', 'P2'].map(pol => [pol, Object.fromEntries(['G', 'N', 'B'].map(k => [k, r3(perSetup.reduce((s, x) => s + x.drawLabel[pol][k], 0))]))])),
      spreadAge5plus: {
        setups: older.length, distinctTop1: Object.keys(topCounts).length, top1Counts: topCounts,
        top1EntropyBits: r3(entropyBits(Object.values(topCounts))),
        P1: spreadOf('P1'), P2: spreadOf('P2'),
        today: 'hero-journey on every book (0 bits)',
      },
      flip: { top1FlipRateBetweenSingleCalls: r3(flips / Math.max(flipPairs, 1)), meanAbsDeltaP: r3(mean(dAbs)), p90AbsDeltaP: r3(pct(dAbs, 0.9)) },
      cost: { calls: allCosts.length, usd: +allCosts.reduce((s, a) => s + a.cost, 0).toFixed(5), usdPerCall: +(mean(allCosts.map(a => a.cost))).toFixed(6), p50ms: pct(allCosts.map(a => a.ms), 0.5), p90ms: pct(allCosts.map(a => a.ms), 0.9) },
      perSetup,
    };
  }
  fs.mkdirSync(RUN_DIR, { recursive: true });
  const prev = fs.existsSync(METRICS) ? JSON.parse(fs.readFileSync(METRICS, 'utf8')) : {};
  fs.writeFileSync(METRICS, JSON.stringify({ ...prev, ...metrics }, null, 1));
  for (const [v, m] of Object.entries(metrics.variants)) {
    const { perSetup, ...head } = m;
    console.log(`\n=== ${v}`, JSON.stringify(head, null, 1));
    for (const s of perSetup) console.log(`${s.setup} ${s.band} today=${s.today}(${s.todayLabel}) | ${s.ranked.map(x => `${x.id}:${x.p}${x.label ? `/${x.label}` : ''}`).join(' ')} | agree ${s.singleTopAgree} | P2 draw ${JSON.stringify(s.draw.P2)}`);
  }
}

// ───────────────────────── STEP 3: can the arc follow a given shape? ─────────────────────────

/**
 * The arc-create prompt with the hero's-journey beats swapped for `shapeId`. Every swap is an
 * exact-string replacement against the REAL rendered prompt and throws when its anchor is missing,
 * so a template change cannot silently turn a shape arm into a baseline arm.
 *   1. the band title                     "# MINI HERO'S JOURNEY (age N)" / "# HERO'S JOURNEY (age N)"
 *   2. the band's subject + mechanics     "**The full shape…** … in that order."
 *   3. the resolution's journey clause    "they come home changed"
 *   4. the CHAIN spec's low-point line    "Near the end one happening is the low point, where the goal looks lost."
 * The shape block then carries the beats; everything else (agency, competence, peril ceiling,
 * opposition, causality, the critique) is the production prompt, untouched.
 */
function swapShape(prompt, shapeId) {
  const s = SHAPES[shapeId];
  const must = (re, label) => { if (!re.test(prompt)) throw new Error(`swapShape: anchor "${label}" not found in the built prompt`); };
  must(/^# (MINI )?HERO'S JOURNEY[^\n]*$/m, 'band title');
  must(/\*\*The full shape[^*]*\.\*\*[\s\S]*?in that order\./, 'subject+mechanics');
  must(/they come home changed/, 'resolution clause');
  must(/Near the end one happening is the low point, where the goal looks lost\./, 'chain low point');
  return prompt
    .replace(/^# (MINI )?HERO'S JOURNEY([^\n]*)$/m, (_, _m, rest) => `# STORY SHAPE: ${s.name.toUpperCase()}${rest}`)
    .replace(/\*\*The full shape[^*]*\.\*\*[\s\S]*?in that order\./, `**The shape of this book: ${s.name}.** ${s.def} Curve: ${s.curve}. Ending: ${s.ending}. Every one of those beats is on the page, in that order.`)
    .replace(/they come home changed/, `they end ${s.ending.replace(/^home — /, 'at home — ')}`)
    .replace(/Near the end one happening is the low point, where the goal looks lost\./, `The happenings follow the shape's curve: ${s.curve}.`);
}

async function llm(prompt, model) {
  const t0 = Date.now();
  const res = await fetch('https://openrouter.ai/api/v1/chat/completions', { method: 'POST',
    headers: { Authorization: `Bearer ${process.env.OPENROUTER_API_KEY}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ model, messages: [{ role: 'user', content: prompt }], usage: { include: true } }) });
  const t = await res.text();
  if (!res.ok) throw new Error(`LLM HTTP ${res.status}: ${t.slice(0, 300)}`);
  const j = JSON.parse(t);
  const text = j.choices?.[0]?.message?.content || '';
  if (!text.trim()) throw new Error('LLM: empty reply');
  return { text, cost: Number(j.usage?.cost || 0), ms: Date.now() - t0, usage: j.usage };
}

async function buildPrompt(it) {
  const { loadPromptTemplates } = require('../../server/services/prompts');
  await loadPromptTemplates();
  const { buildArcCreatePrompt } = require('../../server/lib/promptBuilders');
  // The story's own stored draw (testlab storedChallengeSection's recipe), so both arms see one draw.
  const { CHALLENGE_IDEAS_HEADING } = require('../../server/lib/promptBuilders');
  const stored = String(it.stored.createPrompt || '');
  let challengeIdeas = '';
  const start = stored.search(/^# CHALLENGE IDEAS/m);
  if (start >= 0) {
    const rest = stored.slice(start);
    const next = rest.slice(1).search(/^# /m);
    const lines = (next >= 0 ? rest.slice(0, next + 1) : rest).split('\n');
    const entries = lines.filter(l => /^\s*-\s*\[C\d+\]/.test(l));
    // READ-COMPAT exactly as testlab storedChallengeSection: pre-[C###] draws are bare "- " lines.
    const legacy = lines.filter(l => /^\s*-\s+\S/.test(l));
    if (entries.length) challengeIdeas = [...CHALLENGE_IDEAS_HEADING, '', ...entries].join('\n');
    else if (legacy.length) challengeIdeas = [...CHALLENGE_IDEAS_HEADING.filter(l => !l.includes('[C###]')), '', ...legacy].join('\n');
  }
  if (!challengeIdeas) {
    // No stored draw (older books): draw once with the real drawer, cache it, so every arm and
    // every rerun of this setup sees the identical section.
    const cacheFile = path.join(RUN_DIR, 'challenge-draws.json');
    const cache = fs.existsSync(cacheFile) ? JSON.parse(fs.readFileSync(cacheFile, 'utf8')) : {};
    if (!cache[it.setup]) {
      const { drawChallengeIdeas } = require('../../server/lib/promptBuilders');
      cache[it.setup] = drawChallengeIdeas(it.storyData, {}).section;
      fs.mkdirSync(RUN_DIR, { recursive: true });
      fs.writeFileSync(cacheFile, JSON.stringify(cache, null, 1));
    }
    challengeIdeas = cache[it.setup];
  }
  return buildArcCreatePrompt(it.storyData, it.pageCount, { challengeIdeas });
}

async function arcs() {
  const items = loadItems();
  const model = argv.model || 'google/gemini-3.7-flash';
  const setups = String(argv.setups || '').split(',').filter(Boolean);
  const shapeFor = Object.fromEntries(String(argv.shapes || '').split(',').filter(Boolean).map(x => x.split(':')));
  const capUsd = Number(argv.capUsd || 0.5);
  fs.mkdirSync(RUN_DIR, { recursive: true });
  const prior = fs.existsSync(ARCS) ? fs.readFileSync(ARCS, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse) : [];
  let cost = prior.reduce((s, a) => s + (a.cost || 0), 0);
  const { parseArcCreate } = require('../../server/lib/storyHelpers');
  const jobs = [];
  for (const sid of setups) {
    const it = items.find(x => x.setup === sid);
    if (!it) throw new Error(`no setup ${sid}`);
    const base = await buildPrompt(it);
    if (!base) throw new Error(`${sid}: arc-create prompt not built`);
    const arms = [['baseline', base]];
    for (const sh of String(shapeFor[sid] || '').split('+').filter(Boolean)) arms.push([sh, swapShape(base, sh)]);
    for (const [arm, prompt] of arms) if (!prior.some(p => p.setup === sid && p.arm === arm && p.model === model)) jobs.push({ sid, arm, prompt });
  }
  if (argv.dry) { for (const j of jobs) { const f = path.join(RUN_DIR, `prompt-${j.sid}-${j.arm}.txt`); fs.writeFileSync(f, j.prompt); console.log(`${j.sid} ${j.arm}: ${j.prompt.length} chars → ${path.relative(ROOT, f)}`); } return; }
  console.log(`${jobs.length} arcs to write with ${model} (spent so far $${cost.toFixed(4)}, cap $${capUsd})`);
  await Promise.all(jobs.map(async (j) => {
    if (cost > capUsd) throw new Error(`cap $${capUsd} reached`);
    const r = await llm(j.prompt, model);
    cost += r.cost;
    let parsed = null, parseError = null;
    try { parsed = parseArcCreate(r.text); } catch (e) { parseError = String(e.message || e); }
    fs.appendFileSync(ARCS, JSON.stringify({ setup: j.sid, arm: j.arm, model, cost: r.cost, ms: r.ms, usage: r.usage, promptChars: j.prompt.length, parseError, arc: parsed?.arc || null, logic: parsed?.logic?.text || null, raw: r.text }) + '\n');
    console.log(`${j.sid} ${j.arm}: $${r.cost.toFixed(4)} ${r.ms} ms${parseError ? ` PARSE ERROR ${parseError}` : ''}`);
  }));
  console.log(`total $${cost.toFixed(4)}`);
}

/** Blind pack: per setup, its arcs (baseline + shape arms) shuffled under neutral letters. */
function judgepack() {
  const rows = fs.readFileSync(ARCS, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse);
  const items = loadItems();
  const key = {};
  const pack = [];
  for (const sid of [...new Set(rows.map(r => r.setup))]) {
    const it = items.find(x => x.setup === sid);
    const arms = rows.filter(r => r.setup === sid && r.arc);
    const order = arms.map(a => ({ a, k: crypto.createHash('sha1').update(`${sid}:${a.arm}:shapes-v1`).digest('hex') })).sort((x, y) => (x.k < y.k ? -1 : 1));
    const letters = 'ABCDEFG';
    key[sid] = {};
    pack.push(`\n######## BOOK ${sid} — reader aged ${it.mains[0]?.age}, ${it.pageCount} pages\nTHE COMMISSIONED IDEA: ${it.premise || '(none)'}\n`);
    order.forEach(({ a }, i) => {
      key[sid][letters[i]] = a.arm;
      pack.push(`--- ARC ${sid}-${letters[i]} ---\n${String(a.arc).trim()}\n`);
    });
  }
  // Every shape of the 6+ set, not only the ones used: the judge identifies the shape blind,
  // from distractors too.
  pack.unshift(`# SHAPE DEFINITIONS (for the shape question)\n${BAND_SETS.journey6.map(id => `- ${id}: ${shapeText(id)}`).join('\n')}\n`);
  fs.writeFileSync(path.join(RUN_DIR, 'judge-pack.txt'), pack.join('\n'));
  fs.writeFileSync(path.join(RUN_DIR, 'judge-key.json'), JSON.stringify(key, null, 1));
  console.log(`wrote ${path.relative(ROOT, path.join(RUN_DIR, 'judge-pack.txt'))} (${rows.length} arcs); key kept apart`);
}

/** The judge's answers (letters) mapped back through the key. */
function judgescore() {
  const key = JSON.parse(fs.readFileSync(path.join(RUN_DIR, 'judge-key.json'), 'utf8'));
  const j = JSON.parse(fs.readFileSync(argv.from || path.join(RUN_DIR, 'judge-answers.json'), 'utf8'));
  const out = {};
  const armOf = label => { const [sid, letter] = label.split('-'); return `${sid}:${key[sid][letter]}`; };
  for (const [sid, arcsBy] of Object.entries(j)) {
    if (sid === 'skeletonGroups') continue;
    out[sid] = {};
    for (const [letter, v] of Object.entries(arcsBy)) {
      if (letter === 'better') out[sid].better = v === 'tie' ? 'tie' : key[sid][v];
      else out[sid][key[sid][letter]] = v;
    }
  }
  const groups = (j.skeletonGroups || []).map(g => g.map(armOf));
  const books = Object.keys(out);
  const shapeArms = books.map(sid => ({ sid, arm: Object.keys(out[sid]).find(k => k !== 'baseline' && k !== 'better') }));
  const groupOf = a => groups.findIndex(g => g.includes(a));
  const summary = {
    books: books.length,
    shapeArmIdentifiedAsIntended: shapeArms.filter(({ sid, arm }) => out[sid][arm].shape === arm).length,
    shapeArmIntendedInTop2: shapeArms.filter(({ sid, arm }) => [out[sid][arm].shape, out[sid][arm].runnerUp].includes(arm)).length,
    shapeArmFollows: Object.fromEntries(['yes', 'partly', 'no'].map(k => [k, shapeArms.filter(({ sid, arm }) => out[sid][arm].shape === arm && out[sid][arm].follows === k).length])),
    baselineIdentifiedAsHeroJourney: books.filter(sid => out[sid].baseline?.shape === 'hero-journey').length,
    baselineShapes: books.map(sid => out[sid].baseline?.shape),
    shapeArmShapes: shapeArms.map(({ sid, arm }) => `${arm} → ${out[sid][arm].shape}`),
    heroJourneyFit: { baseline: r3(mean(books.map(sid => out[sid].baseline.heroJourneyFit))), shape: r3(mean(shapeArms.map(({ sid, arm }) => out[sid][arm].heroJourneyFit))) },
    quality: { baseline: r3(mean(books.map(sid => out[sid].baseline.quality))), shape: r3(mean(shapeArms.map(({ sid, arm }) => out[sid][arm].quality))) },
    better: { baseline: books.filter(sid => out[sid].better === 'baseline').length, shape: books.filter(sid => out[sid].better !== 'baseline' && out[sid].better !== 'tie').length, tie: books.filter(sid => out[sid].better === 'tie').length },
    distinctSkeletons: {
      baseline: new Set(books.map(sid => groupOf(`${sid}:baseline`))).size,
      shape: new Set(shapeArms.map(({ sid, arm }) => groupOf(`${sid}:${arm}`))).size,
    },
    skeletonGroups: groups,
  };
  out.summary = summary;
  const prev = fs.existsSync(METRICS) ? JSON.parse(fs.readFileSync(METRICS, 'utf8')) : {};
  const rows = fs.readFileSync(ARCS, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse);
  prev.arcJudge = out;
  prev.arcGeneration = rows.map(r => ({ setup: r.setup, arm: r.arm, model: r.model, cost: r.cost, ms: r.ms, promptChars: r.promptChars, parseError: r.parseError, sentences: (String(r.arc || '').match(/^\s*\d+\./gm) || []).length }));
  fs.writeFileSync(METRICS, JSON.stringify(prev, null, 1));
  console.log(JSON.stringify(out, null, 1));
}

