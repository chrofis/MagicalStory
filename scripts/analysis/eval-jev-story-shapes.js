/** The shape as one prompt-usable block — the ONE string a generator and every critic would read. */
function shapeText(id) {
  const s = SHAPES[id];
  return `${s.name.replace(/^./, c => c.toUpperCase())}. ${s.def} Curve: ${s.curve}. Ending: ${s.ending}.`;
}

function bandSetKey(storyData) {
  const { resolveAgeBand } = require('../../server/lib/promptBuilders');
  const band = resolveAgeBand(storyData);
  if (band !== 'journey') return band;
  const { pickMainCharacters } = require('../../server/lib/promptBuilders');
  const age = parseInt(pickMainCharacters(storyData).focus?.age, 10);
  return Number.isFinite(age) && age <= 5 ? 'journey5' : 'journey6';
}

// ───────────────────────── extract ─────────────────────────

const HEAVY_KEY = /avatar|photo|image|thumbnail|sheet|embedding|faceBox|crop|bbox/i;
function slimCharacter(c) {
  const out = {};
  for (const [k, v] of Object.entries(c || {})) {
    if (HEAVY_KEY.test(k)) continue;
    const s = JSON.stringify(v ?? null);
    if (s.length > 4000 || /data:image|https?:\/\/\S+\.(png|jpe?g|webp)/i.test(s)) continue;
    out[k] = v;
  }
  return out;
}

async function extract() {
  const { Pool } = require('pg');
  const pool = new Pool({ connectionString: process.env.STAGING_DATABASE_URL, ssl: { rejectUnauthorized: false } });
  const KEEP = ['mainCharacters', 'storyCategory', 'storyTopic', 'storyTheme', 'storyType', 'storyDetails', 'language', 'languageLevel', 'pages',
    'userLocation', 'availableLandmarks', 'relationships', 'relationshipTexts', 'title', 'artStyle', 'dedication', 'premiseNamedWorld', 'season', 'storyIdea'];
  const items = [];
  for (const [sid, suffix] of Object.entries(SETUPS)) {
    const { rows: [r] } = await pool.query('SELECT id, data FROM stories WHERE id LIKE $1', [`%${suffix}`]);
    if (!r) throw new Error(`${sid}: story *${suffix} not found on staging`);
    const d = r.data;
    const storyData = { characters: (d.characters || []).map(slimCharacter) };
    for (const k of KEEP) if (d[k] !== undefined) storyData[k] = d[k];
    storyData.pageCount = (d.sceneImages || []).length || d.pages || 10;
    const arc = d.arcReviewReport || {};
    const setKey = bandSetKey(storyData);
    const { pickMainCharacters } = require('../../server/lib/promptBuilders');
    const { mains } = pickMainCharacters(storyData);
    items.push({
      setup: sid, story: r.id, setKey, language: d.language, pageCount: storyData.pageCount,
      mains: mains.map(c => ({ name: c.name, age: c.age })),
      cast: (d.characters || []).map(c => ({ name: c.name, age: c.age, gender: c.gender })),
      premise: String(d.storyDetails || '').trim(),
      storyData,
      stored: { createPrompt: arc.createPrompt || null, finalArc: arc.finalArc || null, creatorModel: arc.creatorModel || null },
    });
    console.log(`${sid} ${r.id}: ${setKey} (mains ${mains.map(c => `${c.name} ${c.age}`).join(', ')}), ${storyData.pageCount}p, premise ${String(d.storyDetails || '').length} chars, stored arc ${arc.finalArc ? 'yes' : 'no'}`);
  }
  await pool.end();
  fs.mkdirSync(DATASET_DIR, { recursive: true });
  fs.writeFileSync(ITEMS, items.map(x => JSON.stringify(x)).join('\n') + '\n');
}

