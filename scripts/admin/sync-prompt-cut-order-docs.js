#!/usr/bin/env node
/**
 * Render the image-prompt cut order into the docs FROM THE CODE.
 *
 * The order the shrinker removes blocks in lives in ONE place:
 * `PROMPT_CUT_ORDER` / `PROMPT_NEVER_CUT` in server/lib/images.js. The two docs
 * that describe it (docs/image-generation-methods.html, docs/prompt-inventory.md)
 * carry a generated section between BEGIN/END markers; this script rewrites it.
 * tests/unit/prompt-cut-order-docs.test.ts fails when a doc is out of date, so
 * the docs can never hold a second, drifting copy.
 *
 *   node scripts/admin/sync-prompt-cut-order-docs.js          # rewrite both docs
 *   node scripts/admin/sync-prompt-cut-order-docs.js --check  # exit 1 if stale
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const BEGIN = '<!-- BEGIN prompt-cut-order (generated by scripts/admin/sync-prompt-cut-order-docs.js from images.js PROMPT_CUT_ORDER; do not edit by hand) -->';
const END = '<!-- END prompt-cut-order -->';

function cutOrder() {
  const { PROMPT_CUT_ORDER, PROMPT_NEVER_CUT } = require('../../server/lib/images');
  const { IMAGE_MODELS } = require('../../server/config/models');
  const grokCaps = [...new Set(Object.values(IMAGE_MODELS)
    .filter(m => m && m.backend === 'grok' && m.maxPromptLength)
    .map(m => m.maxPromptLength))];
  return { steps: PROMPT_CUT_ORDER, neverCut: PROMPT_NEVER_CUT, grokCaps };
}

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const fmt = n => n.toLocaleString('en-US');
const tailLabels = neverCut => neverCut.filter(k => k.marker).map(k => k.label).join(' / ');
const neverCutLead = neverCut => `Never cut. Once every step has run, only the text before the protected tail (from the first of ${tailLabels(neverCut)}) is trimmed, at a sentence boundary; if the tail alone leaves no room, the render fails loudly.`;

function renderHtml({ steps, neverCut, grokCaps }) {
  return [
    BEGIN,
    `<p>Grok image cap: <strong>${grokCaps.map(fmt).join(' / ')} characters</strong> (<code>server/config/models.js</code> <code>maxPromptLength</code>). A built prompt over the cap first has duplicated bullet bodies merged; if it still does not fit, <code>shrinkPromptForModel</code> removes these blocks, <strong>in this order</strong>, stopping as soon as it fits. The generation log names each block it removed, with its step number and size.</p>`,
    '<ol>',
    ...steps.map(s => `  <li><strong>${esc(s.label)}</strong> (~${fmt(s.approxChars)} chars) — ${esc(s.what)}. <em>Why here:</em> ${esc(s.why)}.</li>`),
    '</ol>',
    `<p><strong>${esc(neverCutLead(neverCut))}</strong></p>`,
    '<ul>',
    ...neverCut.map(k => `  <li><strong>${esc(k.label)}</strong> — ${esc(k.why)}</li>`),
    '</ul>',
    END,
  ].join('\n');
}

function renderMarkdown({ steps, neverCut, grokCaps }) {
  return [
    BEGIN,
    `Grok image cap: **${grokCaps.map(fmt).join(' / ')} characters** (\`server/config/models.js\` \`maxPromptLength\`). Over the cap, duplicated bullet bodies are merged first; then \`shrinkPromptForModel\` removes these blocks **in this order**, stopping as soon as the prompt fits. The generation log names each removed block with its step number and size.`,
    '',
    ...steps.map((s, i) => `${i + 1}. **${s.label}** (~${fmt(s.approxChars)} chars) — ${s.what}. *Why here:* ${s.why}.`),
    '',
    `**${neverCutLead(neverCut)}**`,
    '',
    ...neverCut.map(k => `- **${k.label}** — ${k.why}`),
    END,
  ].join('\n');
}

const DOCS = [
  { file: 'docs/image-generation-methods.html', render: renderHtml },
  { file: 'docs/prompt-inventory.md', render: renderMarkdown },
];

/** The doc's text with its generated section replaced. Throws if the markers are missing. */
function withSection(text, section, file) {
  const nl = text.includes('\r\n') ? '\r\n' : '\n';
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  if (b < 0 || e < b) throw new Error(`${file}: no prompt-cut-order BEGIN/END markers`);
  return text.slice(0, b) + section.split('\n').join(nl) + text.slice(e + END.length);
}

function sync({ check = false } = {}) {
  const data = cutOrder();
  const stale = [];
  for (const { file, render } of DOCS) {
    const abs = path.join(ROOT, file);
    const text = fs.readFileSync(abs, 'utf8');
    const next = withSection(text, render(data), file);
    if (next !== text) {
      stale.push(file);
      if (!check) fs.writeFileSync(abs, next);
    }
  }
  return stale;
}

module.exports = { renderHtml, renderMarkdown, withSection, cutOrder, sync, DOCS, BEGIN, END };

if (require.main === module) {
  const check = process.argv.includes('--check');
  const stale = sync({ check });
  if (check && stale.length) {
    console.error(`prompt cut order docs are stale: ${stale.join(', ')} — run node scripts/admin/sync-prompt-cut-order-docs.js`);
    process.exit(1);
  }
  console.log(stale.length ? `${check ? 'stale' : 'updated'}: ${stale.join(', ')}` : 'prompt cut order docs are up to date');
  process.exit(0);
}
